/**
 * Citation topics (CR audit tool 1.5b).
 *
 * Every CR citation in src/ — a literal `CR n.n…`, a `CR.<key>` use, and
 * each label in src/timing/labels.ts — is compared with the rule it cites.
 * The code's words (the comment clause, or for log lines and cite lists the
 * enclosing function and nearby code) are matched against the plan's
 * topics, widened by the CR's own defined terms. The rule's words are its
 * text, its titles, its section, and the CR's `{term:…}` vocabulary. A
 * mismatch is code about a plan topic that the cited rule's whole section
 * never mentions and that shares no topic or rare CR word with the rule.
 * See tests/cr-citations.ts for the model.
 *
 * Tuned for precision over recall. Mismatches are recorded in
 * tests/baselines/cr-citation-topics.json, keyed by file, cited number
 * (and label), and topic — not line — and the cr-checker review list is
 * tests/generated/cr-citation-topics-review.md. Regenerate both with
 *   UPDATE_CR_CITATION_TOPICS=1 npx vitest run tests/cr-citation-topics.test.ts
 *
 * The test fails on a mismatch that is not recorded, and on a recorded one
 * that is gone. Phase 2 of the plan stops new mismatches from being
 * recorded once cr-checker has reviewed this baseline.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { assertPinnedTag, crDataPresent } from "../src/index.js";
import {
  buildTopicModel,
  loadNodes,
  mismatchKey,
  ROOT,
  scanCitations,
  topicMismatch,
  topicsOf,
  type TopicMismatch,
} from "./cr-citations.js";

beforeAll(() => {
  if (!crDataPresent()) throw new Error("Run npm run fetch-cr");
  assertPinnedTag("v26.03");
});

const BASELINE_PATH = join(ROOT, "tests/baselines/cr-citation-topics.json");
const REVIEW_PATH = join(ROOT, "tests/generated/cr-citation-topics-review.md");
const REGENERATE =
  "UPDATE_CR_CITATION_TOPICS=1 npx vitest run tests/cr-citation-topics.test.ts";

function compute() {
  const model = buildTopicModel(loadNodes());
  const citations = scanCitations();
  const mismatches = citations
    .map((c) => topicMismatch(model, c))
    .filter((m): m is TopicMismatch => m !== null);
  return { model, citations, mismatches };
}

function describeSite(m: TopicMismatch): string {
  return (
    `${m.file}:${m.line} cites CR ${m.number}${m.label ? ` (${m.label})` : ""}; ` +
    `code topic ${m.topic}; rule: ${m.ruleTitle}; code: "${m.subject.trim().slice(0, 120)}"`
  );
}

function baselineJson(keys: string[]): string {
  return (
    JSON.stringify(
      {
        _comment:
          "Citation-topic mismatches (CR audit tool 1.5b, tests/cr-citation-topics.test.ts). " +
          "Each entry is `<file> CR <number> [(CR.<label>)] [<code topic>]`: code about that " +
          "topic citing a rule whose section never mentions it. Generated; regenerate with " +
          `${REGENERATE}. Review with cr-checker via tests/generated/cr-citation-topics-review.md.`,
        mismatches: keys,
      },
      null,
      2,
    ) + "\n"
  );
}

/** cr-checker review list: mismatches grouped by cited number, most frequent first. */
function reviewMarkdown(mismatches: TopicMismatch[]): string {
  const groups = new Map<string, TopicMismatch[]>();
  for (const m of mismatches) groups.set(m.number, [...(groups.get(m.number) ?? []), m]);
  const ordered = [...groups.entries()].sort(
    ([a, x], [b, y]) => y.length - x.length || a.localeCompare(b, "en", { numeric: true }),
  );
  const out: string[] = [
    "# CR citation topics: cr-checker review list",
    "",
    "Generated by `tests/cr-citation-topics.test.ts` (CR audit tool 1.5b). Do not edit by hand;",
    `regenerate with \`${REGENERATE}\`.`,
    "",
    "Each group is one cited rule number, most flagged sites first. Run the cr-checker agent over",
    "the top groups: for each site, say whether the citation is wrong, and which rule fits. Line",
    "numbers are left out so edits elsewhere do not churn this file; `grep -n \"CR <number>\" <file>`",
    "finds the site.",
    "",
    `${mismatches.length} sites in ${ordered.length} groups.`,
    "",
  ];
  ordered.forEach(([number, ms], i) => {
    out.push(`## ${i + 1}. CR ${number} — ${ms.length} site${ms.length === 1 ? "" : "s"}`);
    out.push("");
    out.push(`Rule: ${ms[0]!.ruleTitle}`);
    out.push("");
    out.push("| File | Via | Code topic | Sites |");
    out.push("| --- | --- | --- | --- |");
    const rows = new Map<string, number>();
    for (const m of ms) {
      const row = `| \`${m.file}\` | ${m.label ? `\`${m.label}\`` : "literal"} | ${m.topic} |`;
      rows.set(row, (rows.get(row) ?? 0) + 1);
    }
    for (const [row, n] of [...rows].sort(([a], [b]) => a.localeCompare(b))) {
      out.push(`${row} ${n} |`);
    }
    out.push("");
  });
  return out.join("\n");
}

describe("CR citation topics (CR audit 1.5b)", () => {
  const { model, citations, mismatches } = compute();
  const found = [...new Set(mismatches.map(mismatchKey))].sort();

  if (process.env.UPDATE_CR_CITATION_TOPICS) {
    writeFileSync(BASELINE_PATH, baselineJson(found));
    mkdirSync(dirname(REVIEW_PATH), { recursive: true });
    writeFileSync(REVIEW_PATH, reviewMarkdown(mismatches));
    for (const m of mismatches) console.log(describeSite(m));
  }

  it("scans literal citations, CR.<key> uses, and the labels themselves", () => {
    const literal = citations.filter((c) => !c.label);
    const uses = citations.filter((c) => c.label && c.where !== "label");
    const labels = citations.filter((c) => c.where === "label");
    expect(literal.length).toBeGreaterThan(1000);
    expect(uses.length).toBeGreaterThan(1000);
    expect(labels.length).toBeGreaterThan(300);
  });

  it("reads the topic vocabulary from the CR as well as the plan", () => {
    // "hidden information" is a defined term of CR 10.2, not a plan word.
    expect(topicsOf(model, "hidden information")).toContain("visibility");
    // Section titles become topics: CR 10.8 Traces.
    expect(topicsOf(model, "the trace strength")).toContain("§10.8");
  });

  it("flags every CR 1.18 citation used for card visibility (now CR 1.21)", () => {
    const cites118 = citations.filter((c) => /^1\.18(?:\.|$)/.test(c.number) && !c.label);
    const visibility = cites118.filter((c) => topicsOf(model, c.subject).has("visibility"));
    const flagged = mismatches.filter((m) => /^1\.18(?:\.|$)/.test(m.number));
    expect(visibility.map((c) => `${c.file} ${c.number}`).sort()).toEqual([
      "src/api/library.ts 1.18.1",
      "src/state/seatVisibility.ts 1.18",
      "src/state/types.ts 1.18.1",
    ]);
    expect(flagged.map((m) => `${m.file}:${m.line}`).sort()).toEqual(
      visibility.map((c) => `${c.file}:${c.line}`).sort(),
    );
    expect(flagged.every((m) => m.topic.split("+").includes("visibility"))).toBe(true);
    // The other CR 1.18 citations are about advancing, and are not flagged.
    expect(cites118.length - visibility.length).toBeGreaterThan(0);
  });

  const baseline = (): string[] =>
    (JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as { mismatches: string[] }).mismatches;

  it("fails on a mismatch the baseline does not record", () => {
    const recorded = baseline();
    expect(recorded, "baseline must stay sorted").toEqual([...recorded].sort());
    const fresh = mismatches.filter((m) => !recorded.includes(mismatchKey(m)));
    expect(
      fresh.map(describeSite),
      "CR citation(s) whose rule is about something else: fix the number, or record " +
        `them for cr-checker review with ${REGENERATE}`,
    ).toEqual([]);
  });

  it("fails on a recorded mismatch that is gone (shrink-only)", () => {
    expect(
      baseline().filter((k) => !found.includes(k)),
      `recorded mismatch(es) no longer found: regenerate with ${REGENERATE}`,
    ).toEqual([]);
  });

  it("keeps the cr-checker review list in step with the baseline", () => {
    expect(
      readFileSync(REVIEW_PATH, "utf8"),
      `tests/generated/cr-citation-topics-review.md is stale: regenerate with ${REGENERATE}`,
    ).toBe(reviewMarkdown(mismatches));
  });
});
