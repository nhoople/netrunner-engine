/**
 * CR example coverage (CR audit tool 1.6).
 *
 * Lists every example at the pin (nodes with `kind: "example"` in
 * vendor/cr-data/nodes.json, numbered like `6.2.3.ex1`) and the `it()`
 * titles in tests/cr-examples-ch*.test.ts that cite each one. A citation in
 * a comment does not count: the example needs a test named for it.
 *
 * - Unreferenced examples are in tests/baselines/cr-examples.json, which may
 *   only shrink.
 * - tests/generated/cr-example-coverage.json is the per-chapter table that
 *   Phase 3 reads. It must match what this test computes. Regenerate with
 *     UPDATE_CR_EXAMPLE_COVERAGE=1 npx vitest run tests/cr-example-coverage.test.ts
 *
 * This checks presence only. Whether a test is adequate is tool 1.9.
 */
import { mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { assertPinnedTag, crDataPresent } from "../src/index.js";

beforeAll(() => {
  if (!crDataPresent()) throw new Error("Run npm run fetch-cr");
  assertPinnedTag("v26.03");
});

const ROOT = process.cwd();
const BASELINE_PATH = join(ROOT, "tests/baselines/cr-examples.json");
const TABLE_PATH = join(ROOT, "tests/generated/cr-example-coverage.json");

type CrNode = {
  id: string;
  kind: string;
  number: string;
  title: string | null;
  parent_id: string | null;
};

type Coverage = {
  _comment: string;
  crTag: string;
  totals: { examples: number; referenced: number; unreferenced: number };
  chapters: Array<{
    chapter: string;
    title: string;
    examples: number;
    referenced: number;
    unreferenced: string[];
  }>;
  /** example number -> `file › it title` for each test that cites it */
  examples: Record<string, string[]>;
};

/** Compare CR numbers part by part: 1.4.5a.ex1 < 1.10.3b.ex1 < 2.1.1.ex1. */
function compareNumbers(a: string, b: string): number {
  const pa = a.split(".");
  const pb = b.split(".");
  for (let i = 0; i < Math.max(pa.length, pb.length); i++) {
    const x = pa[i] ?? "";
    const y = pb[i] ?? "";
    if (x === y) continue;
    const nx = parseInt(x.replace(/^ex/, ""), 10);
    const ny = parseInt(y.replace(/^ex/, ""), 10);
    if (nx !== ny && !Number.isNaN(nx) && !Number.isNaN(ny)) return nx - ny;
    return x < y ? -1 : 1;
  }
  return 0;
}

function exampleCitations(): Map<string, string[]> {
  const out = new Map<string, string[]>();
  const files = readdirSync(join(ROOT, "tests"))
    .filter((f) => /^cr-examples-ch\d+\.test\.ts$/.test(f))
    .sort((a, b) => a.localeCompare(b, "en", { numeric: true }));
  // it("…"), it.skip('…'), it(`…`) — the title is the first argument.
  const IT = /\bit(?:\.\w+)?\(\s*(["'`])((?:\\.|(?!\1)[\s\S])*?)\1/g;
  // 6.2.3.ex1, plus follow-ons like `6.2.3.ex1, ex2` or `6.2.3.ex1–3`.
  const EX = /(\d+(?:\.\d+)*[a-z]?)\.ex(\d+)((?:\s*(?:,|–|-|\/|and)\s*(?:ex)?\d+)*)/g;
  for (const file of files) {
    const text = readFileSync(join(ROOT, "tests", file), "utf8");
    for (const m of text.matchAll(IT)) {
      const title = m[2]!;
      for (const r of title.matchAll(EX)) {
        for (const n of [r[2]!, ...(r[3]!.match(/\d+/g) ?? [])]) {
          const number = `${r[1]}.ex${n}`;
          if (!out.has(number)) out.set(number, []);
          out.get(number)!.push(`${file} › ${title}`);
        }
      }
    }
  }
  return out;
}

function computeCoverage(): Coverage {
  const nodes = JSON.parse(
    readFileSync(join(ROOT, "vendor/cr-data/nodes.json"), "utf8"),
  ) as CrNode[];
  const pin = JSON.parse(
    readFileSync(join(ROOT, "vendor/cr-data/PIN.json"), "utf8"),
  ) as { tag?: string };
  const examples = nodes
    .filter((n) => n.kind === "example")
    .map((n) => n.number)
    .sort(compareNumbers);
  const chapters = nodes
    .filter((n) => n.kind === "chapter")
    .sort((a, b) => compareNumbers(a.number, b.number));
  const cited = exampleCitations();

  const unknown = [...cited.keys()].filter((k) => !examples.includes(k));
  expect(unknown, "it() titles cite examples that do not exist at the pin").toEqual([]);

  const byExample: Record<string, string[]> = {};
  for (const ex of examples) byExample[ex] = cited.get(ex) ?? [];
  const referenced = examples.filter((ex) => byExample[ex]!.length > 0);

  return {
    _comment:
      "Generated by tests/cr-example-coverage.test.ts (CR audit tool 1.6). " +
      "Do not edit by hand; regenerate with UPDATE_CR_EXAMPLE_COVERAGE=1.",
    crTag: pin.tag ?? "",
    totals: {
      examples: examples.length,
      referenced: referenced.length,
      unreferenced: examples.length - referenced.length,
    },
    chapters: chapters.map((c) => {
      const mine = examples.filter((ex) => ex.split(".")[0] === c.number);
      return {
        chapter: c.number,
        title: c.title ?? "",
        examples: mine.length,
        referenced: mine.filter((ex) => byExample[ex]!.length > 0).length,
        unreferenced: mine.filter((ex) => byExample[ex]!.length === 0),
      };
    }),
    examples: byExample,
  };
}

describe("CR example coverage (CR audit 1.6)", () => {
  const coverage = computeCoverage();

  it("finds every example at the pin", () => {
    expect(coverage.totals.examples).toBe(243);
    expect(coverage.crTag).toBe("v26.03");
  });

  it("every example is cited by an it() title, or is in the shrink-only baseline", () => {
    const baseline = (
      JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as { unreferenced: string[] }
    ).unreferenced;
    const unreferenced = coverage.chapters.flatMap((c) => c.unreferenced);
    expect(
      unreferenced.filter((ex) => !baseline.includes(ex)),
      "CR example(s) with no it() title citing them: add a test in " +
        "tests/cr-examples-chN.test.ts, or record it in " +
        "tests/baselines/cr-examples.json with a reason",
    ).toEqual([]);
    expect(
      baseline.filter((ex) => !unreferenced.includes(ex)),
      "example(s) now cited: remove from tests/baselines/cr-examples.json",
    ).toEqual([]);
  });

  it("the generated per-chapter table is current", () => {
    const want = `${JSON.stringify(coverage, null, 2)}\n`;
    if (process.env.UPDATE_CR_EXAMPLE_COVERAGE) {
      mkdirSync(dirname(TABLE_PATH), { recursive: true });
      writeFileSync(TABLE_PATH, want);
    }
    expect(
      readFileSync(TABLE_PATH, "utf8"),
      "tests/generated/cr-example-coverage.json is stale; regenerate with " +
        "UPDATE_CR_EXAMPLE_COVERAGE=1 npx vitest run tests/cr-example-coverage.test.ts",
    ).toBe(want);
  });
});
