/**
 * The legality agreement check in the seeded playouts: at every position a
 * playout reaches, the legal-action list must offer exactly the moves
 * `applyAction` accepts (`src/debug/legalityAgreement.ts`). The match host
 * takes only listed moves, so a move apply accepts but the list leaves out
 * can never be made at the table.
 *
 * What a format's seeds find is recorded in
 * `tests/baselines/legality-agreement/<format>.json`, one entry per
 * disagreement key with a first example. The baseline only shrinks: a new
 * key fails, and so does a recorded key that no longer happens. Regenerate
 * with `UPDATE_LEGALITY_AGREEMENT=1 npx vitest run tests/legality-agreement`.
 */
import { existsSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { fileURLToPath } from "node:url";
import { beforeAll, describe, expect, it } from "vitest";
import { cardsDataPresent, crDataPresent } from "../../src/index.js";
import {
  disagreementKey,
  legalityDisagreements,
} from "../../src/debug/legalityAgreement.js";
import { PLAYOUT_STEPS, playout, type Format } from "./harness.js";

const ROOT = fileURLToPath(new URL("../..", import.meta.url));
const DIR = join(ROOT, "tests/baselines/legality-agreement");

/** Seeds per format. Each position tries every probe, so keep this small. */
const AGREEMENT_SEEDS = 1;

type Found = Record<string, string>;
interface Baseline {
  _comment: string;
  seeds: Record<string, Found>;
}

function baselinePath(format: Format): string {
  return join(DIR, `${format}.json`);
}

function readBaseline(format: Format): Baseline {
  const path = baselinePath(format);
  if (!existsSync(path)) return { _comment: "", seeds: {} };
  return JSON.parse(readFileSync(path, "utf8")) as Baseline;
}

/** Every disagreement key `format`'s `seed` finds, with a first example. */
function agreementFindings(format: Format, seed: number): Found {
  const found: Found = {};
  playout(format, seed, PLAYOUT_STEPS, (state, step) => {
    for (const d of legalityDisagreements(state)) {
      const key = disagreementKey(d);
      found[key] ??= `step ${step}: ${JSON.stringify(d.action)}: ${d.detail}`;
    }
  });
  return found;
}

/** The differences between what a seed found and its baseline entry. */
function compareAgreement(found: Found, recorded: Found): string[] {
  const errors: string[] = [];
  for (const [key, example] of Object.entries(found)) {
    if (!(key in recorded)) errors.push(`new disagreement ${key} (${example})`);
  }
  for (const key of Object.keys(recorded)) {
    if (!(key in found)) {
      errors.push(
        `${key} is in the baseline but no longer happens: remove it ` +
          "(UPDATE_LEGALITY_AGREEMENT=1 npx vitest run tests/legality-agreement)",
      );
    }
  }
  return errors;
}

export function describeAgreement(formats: readonly Format[]): void {
  beforeAll(() => {
    if (!crDataPresent()) throw new Error("Run npm run fetch-cr");
    if (!cardsDataPresent()) throw new Error("Run npm run fetch-cards");
  });
  for (const format of formats) {
    describe(`legality agreement, ${format}`, () => {
      it(`the legal-action list offers exactly the moves apply accepts, seeds 1-${AGREEMENT_SEEDS}`, () => {
        const baseline = readBaseline(format);
        const seeds: Record<string, Found> = {};
        const errors: string[] = [];
        for (let seed = 1; seed <= AGREEMENT_SEEDS; seed++) {
          const found = agreementFindings(format, seed);
          seeds[String(seed)] = Object.fromEntries(
            Object.entries(found).sort(([a], [b]) => a.localeCompare(b)),
          );
          for (const e of compareAgreement(
            found,
            baseline.seeds[String(seed)] ?? {},
          ))
            errors.push(`seed ${seed}: ${e}`);
        }
        if (process.env.UPDATE_LEGALITY_AGREEMENT) {
          const out: Baseline = {
            _comment:
              "Generated by tests/playout/agreement.ts. Shrink-only: each key is a move the legal-action list and applyAction disagree on (code, action, window, card).",
            seeds,
          };
          writeFileSync(
            baselinePath(format),
            `${JSON.stringify(out, null, 2)}\n`,
          );
          return;
        }
        expect(errors).toEqual([]);
      }, 300_000);
    });
  }
}
