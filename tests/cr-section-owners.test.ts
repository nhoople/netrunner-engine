/**
 * CR section owners (CR audit tool 1.13).
 *
 * Every section (`n.n`, `kind: "section"` in vendor/cr-data/nodes.json) at
 * the CR pin has one owner in tests/cr-section-owners.json: an area of the
 * CR audit plan (`area 1` … `area 16`), an earlier program (`fidelity` or
 * `standardization`, re-audited by RA-1 and RA-2), `reference`, or `none`.
 * A section split between owners lists its other owners by subrule.
 *
 * - A section at the pin missing from the table fails, so a CR pin bump
 *   shows its new sections.
 * - Sections marked `none` are in tests/baselines/cr-section-owners.json,
 *   which may only shrink.
 * - tests/generated/cr-section-owners.md is the table with, per section,
 *   the src/ citations (the 1.5 map, tests/cr-citations.ts) and the test
 *   files that cite it. It must match what this test computes. Regenerate
 *   with
 *     UPDATE_CR_SECTION_OWNERS=1 npx vitest run tests/cr-section-owners.test.ts
 *
 * This checks that each section has an owner. It does not check subrules
 * (tool 1.17), interactions between cards, or whether a rule is played right.
 */
import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { beforeAll, describe, expect, it } from "vitest";
import { assertPinnedTag, crDataPresent } from "../src/index.js";
import {
  compareNumbers,
  type CrNode,
  literalCitations,
  loadNodes,
  ROOT,
  scanCitations,
  testFiles,
} from "./cr-citations.js";
import {
  loadOwnerTable,
  OWNER,
  ownerRank,
  type OwnerTable,
  sectionOf,
  within,
} from "./cr-owners.js";

beforeAll(() => {
  if (!crDataPresent()) throw new Error("Run npm run fetch-cr");
  assertPinnedTag("v26.03");
});

const BASELINE_PATH = join(ROOT, "tests/baselines/cr-section-owners.json");
const GENERATED_PATH = join(ROOT, "tests/generated/cr-section-owners.md");
const SELF = "tests/cr-section-owners.test.ts";

type Row = {
  number: string;
  title: string;
  owner: string;
  subrules: Array<[string, string]>;
  srcCites: number;
  testCites: number;
  testFiles: number;
};

function computeRows(sections: CrNode[], table: OwnerTable): Row[] {
  const srcCites = new Map<string, number>();
  for (const c of scanCitations()) {
    // A label's own definition in src/timing/labels.ts is not a use of it.
    if (c.where === "label") continue;
    const s = sectionOf(c.number);
    if (s) srcCites.set(s, (srcCites.get(s) ?? 0) + 1);
  }
  const testCites = new Map<string, number>();
  const testFileCount = new Map<string, number>();
  for (const file of testFiles(SELF)) {
    const mine = new Set<string>();
    for (const { number } of literalCitations(readFileSync(file, "utf8"))) {
      const s = sectionOf(number);
      if (!s) continue;
      testCites.set(s, (testCites.get(s) ?? 0) + 1);
      mine.add(s);
    }
    for (const s of mine) testFileCount.set(s, (testFileCount.get(s) ?? 0) + 1);
  }
  return sections.map((sec) => {
    const entry = table.sections[sec.number];
    return {
      number: sec.number,
      title: sec.title ?? "",
      owner: entry?.owner ?? "(missing)",
      subrules: Object.entries(entry?.subrules ?? {}).sort(([a], [b]) =>
        compareNumbers(a, b),
      ),
      srcCites: srcCites.get(sec.number) ?? 0,
      testCites: testCites.get(sec.number) ?? 0,
      testFiles: testFileCount.get(sec.number) ?? 0,
    };
  });
}

function render(rows: Row[], crTag: string): string {
  const owners = [...new Set(rows.map((r) => r.owner))].sort(
    (a, b) => ownerRank(a) - ownerRank(b),
  );
  const subOwners = new Map<string, string[]>();
  for (const r of rows) {
    for (const [n, o] of r.subrules) {
      subOwners.set(o, [...(subOwners.get(o) ?? []), n]);
    }
  }
  const none = rows.filter((r) => r.owner === "none").map((r) => r.number);
  const lines = [
    "# CR section owners",
    "",
    `Generated by \`tests/cr-section-owners.test.ts\` (CR audit tool 1.13) from \`tests/cr-section-owners.json\` and the CR \`${crTag}\` sections. Do not edit by hand; regenerate with \`UPDATE_CR_SECTION_OWNERS=1 npx vitest run tests/cr-section-owners.test.ts\`.`,
    "",
    "Each CR section has one owner: an area of the CR audit plan, an earlier program (`fidelity`, `standardization`), `reference`, or `none`. A split section names the subrules another owner takes. Citations: `src/` counts each `CR n.n…` and `CR.<key>` use in `src/` (the 1.5 citation map); tests counts each literal `CR n.n…` in `tests/**/*.test.ts` (not `tests/jnet`) and the files they are in. A citation of a subrule counts for its section. The counts are a snapshot from the last regeneration; the test checks the owners, not the counts.",
    "",
    "## Sections per owner",
    "",
    "| Owner | Sections | Subrules taken from another owner's section |",
    "|---|---|---|",
    ...owners.map((o) => {
      const secs = rows.filter((r) => r.owner === o).map((r) => r.number);
      const subs = (subOwners.get(o) ?? []).sort(compareNumbers);
      return `| ${o} | ${secs.length}: ${secs.join(", ")} | ${subs.join(", ") || "—"} |`;
    }),
    ...[...subOwners.keys()]
      .filter((o) => !owners.includes(o))
      .sort((a, b) => ownerRank(a) - ownerRank(b))
      .map(
        (o) =>
          `| ${o} | 0 | ${(subOwners.get(o) ?? []).sort(compareNumbers).join(", ")} |`,
      ),
    "",
    `**Total:** ${rows.length} sections. **No owner (\`none\`):** ${none.length ? none.join(", ") : "none"}.`,
    "",
    "## Sections",
    "",
    "| Section | Title | Owner | Split subrules | `src/` cites | Test cites | Test files |",
    "|---|---|---|---|---|---|---|",
    ...rows.map(
      (r) =>
        `| ${r.number} | ${r.title} | ${r.owner} | ${
          r.subrules.map(([n, o]) => `${n} → ${o}`).join("; ") || ""
        } | ${r.srcCites} | ${r.testCites} | ${r.testFiles} |`,
    ),
    "",
  ];
  return lines.join("\n");
}

/** The generated table without its citation-count columns. */
function ownerView(md: string): string {
  return md
    .split("\n")
    .map((l) =>
      /^\| \d+\.\d+ \|/.test(l) ? l.split(" | ").slice(0, 4).join(" | ") : l,
    )
    .join("\n");
}

describe("CR section owners (CR audit 1.13)", () => {
  const nodes = loadNodes();
  const byNumber = new Map(nodes.map((n) => [n.number, n]));
  const sections = nodes
    .filter((n) => n.kind === "section")
    .sort((a, b) => compareNumbers(a.number, b.number));
  const table = loadOwnerTable();
  const pin = JSON.parse(
    readFileSync(join(ROOT, "vendor/cr-data/PIN.json"), "utf8"),
  ) as { tag?: string };

  it("reads every section at the pin", () => {
    expect(pin.tag).toBe("v26.03");
    expect(table.crTag).toBe(pin.tag);
    expect(sections.length).toBe(119);
  });

  it("every CR section at the pin has an owner", () => {
    const missing = sections
      .filter((s) => !(s.number in table.sections))
      .map((s) => `${s.number} ${s.title ?? ""}`);
    expect(
      missing,
      "CR section(s) at the pin with no entry in tests/cr-section-owners.json: " +
        "give each an owner (an area, fidelity, standardization, reference, " +
        "or none with a dated decision in the baseline)",
    ).toEqual([]);
  });

  it("the owner table names only sections at the pin, each with a valid owner and a reason", () => {
    const problems: string[] = [];
    for (const [number, entry] of Object.entries(table.sections)) {
      if (byNumber.get(number)?.kind !== "section") {
        problems.push(`${number}: not a section at the pin`);
      }
      if (!OWNER.test(entry.owner)) {
        problems.push(`${number}: owner "${entry.owner}" is not valid`);
      }
      if (!entry.why?.trim()) problems.push(`${number}: no "why"`);
    }
    expect(problems).toEqual([]);
  });

  it("a split section gives each of its subrules, none nested in another, to another owner", () => {
    const problems: string[] = [];
    for (const [number, entry] of Object.entries(table.sections)) {
      const subs = Object.keys(entry.subrules ?? {});
      for (const a of subs) {
        for (const b of subs) {
          if (a !== b && within(a, b)) {
            problems.push(`${number}: subrule ${a} is nested in ${b}`);
          }
        }
      }
      for (const [sub, owner] of Object.entries(entry.subrules ?? {})) {
        const node = byNumber.get(sub);
        if (!node || node.kind === "section" || node.kind === "example") {
          problems.push(`${number}: subrule ${sub} is not a rule at the pin`);
        } else if (sectionOf(sub) !== number) {
          problems.push(`${number}: subrule ${sub} is in another section`);
        }
        if (!OWNER.test(owner) || owner === "none") {
          problems.push(
            `${number}: subrule ${sub} owner "${owner}" is not valid`,
          );
        }
        if (owner === entry.owner) {
          problems.push(
            `${number}: subrule ${sub} repeats the section's owner`,
          );
        }
      }
    }
    expect(problems).toEqual([]);
  });

  it("sections with no owner are only those in the shrink-only baseline", () => {
    const baseline = (
      JSON.parse(readFileSync(BASELINE_PATH, "utf8")) as { none: string[] }
    ).none;
    const none = Object.entries(table.sections)
      .filter(([, e]) => e.owner === "none")
      .map(([n]) => n)
      .sort(compareNumbers);
    expect(
      none.filter((n) => !baseline.includes(n)),
      "CR section(s) marked none: give each an owner, or record it in " +
        "tests/baselines/cr-section-owners.json with a dated decision",
    ).toEqual([]);
    expect(
      baseline.filter((n) => !none.includes(n)),
      "section(s) now owned: remove from tests/baselines/cr-section-owners.json",
    ).toEqual([]);
  });

  it("the generated section table shows the current owners", () => {
    const want = render(computeRows(sections, table), table.crTag);
    if (process.env.UPDATE_CR_SECTION_OWNERS) {
      mkdirSync(dirname(GENERATED_PATH), { recursive: true });
      writeFileSync(GENERATED_PATH, want);
    }
    // The citation counts are a snapshot from the last regeneration: any PR
    // that adds a citation changes them, and it need not regenerate this
    // file. The owners must always match.
    expect(
      ownerView(readFileSync(GENERATED_PATH, "utf8")),
      "tests/generated/cr-section-owners.md is stale; regenerate with " +
        "UPDATE_CR_SECTION_OWNERS=1 npx vitest run tests/cr-section-owners.test.ts",
    ).toBe(ownerView(want));
  });
});
